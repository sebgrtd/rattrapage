async function until(condition: () => boolean, timeout = 4000) {
  const end = performance.now() + timeout;
  while (!condition() && performance.now() < end) await delay(25);
  assert.ok(condition(), 'Condition not reached before timeout');
}
test('interactive scenarios produce real protocol changes without modifying unrelated devices', () => {
  let now = 0; const sim = new InteractiveSimulation(2, () => now);
  const read = () => sim.frames().map(bytes => { const result = decode(bytes); assert.ok(result.ok); return result.frame; });
  assert.equal(read().length, 2);
  sim.act(1, 'heat'); now = 500;
  let frames = read(); assert.ok(frames[0]!.measurements[0]!.value > 7000); assert.ok(frames[1]!.measurements[0]!.value < 7000);
  sim.act(1, 'stop'); now = 1200; assert.deepEqual(read().map(f => f.deviceId), [2]);
  sim.act(1, 'resume'); frames = read(); assert.equal(frames[0]!.seq, 3); assert.equal(frames[0]!.uptimeMs, 1200);
  now = 1300; read(); sim.act(1, 'restart'); assert.equal(sim.snapshot()[0]!.status, 'restarting');
  assert.throws(() => sim.act(1, 'resume'), /en cours/);
  now = 2299; assert.deepEqual(read().map(f => f.deviceId), [2]);
  now = 2300; frames = read(); assert.equal(frames[0]!.seq, 1); assert.equal(frames[0]!.uptimeMs, 0);
  assert.ok(frames[0]!.measurements[0]!.value > 7000, 'Restart preserves the physical temperature scenario');
  assert.throws(() => sim.act(1, 'restart'), /1 seconde/);
  sim.act(1, 'normal'); assert.ok(read()[0]!.measurements[0]!.value < 7000);
  assert.throws(() => sim.act(999, 'stop'), /inconnu/);
});
test('HTTP control → UDP → hub confirms alert, outage, recovery and reboot; local API rejects invalid commands', { timeout: 15000 }, async t => {
  const config = { ...loadConfig(), udpPort: 0, httpPort: 0, historyFile: '', staleMs: 200, offlineMs: 300 };
  config.alerts = config.alerts.map(a => ({ ...a, durationMs: 150 }));
  const hub = await startHub(config); t.after(() => hub.close());
  const demo = await startInteractiveDemo({ devices: 2, hz: 20, controlPort: 0, udpPort: (hub.udp.address() as AddressInfo).port, hubPort: (hub.http.address() as AddressInfo).port });
  t.after(() => demo.close());
  const base = `http://127.0.0.1:${(demo.server.address() as AddressInfo).port}`;
  const action = (name: string, extraHeaders: Record<string, string> = {}, id = 1) => fetch(base + '/api/action', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base, ...extraHeaders }, body: JSON.stringify({ deviceId: id, action: name }) });
  const device = () => hub.snapshot().devices.find(d => d.id === 1);
  await until(() => hub.snapshot().totals.online === 2 && demo.snapshot().hub.connected);
  assert.equal((await fetch(base)).status, 200);
  const initial = hub.snapshot().counters.received;
  assert.equal((await action('heat', { Origin: 'https://external.example' })).status, 403);
  assert.equal((await action('heat', { 'Content-Type': 'text/plain' })).status, 415);
  assert.equal((await action('unknown')).status, 400);
  assert.equal((await action('heat', {}, 999)).status, 409);
  assert.equal((await fetch(base + '/api/action', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{' })).status, 400);
  assert.equal((await fetch(base + '/api/action', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: ' '.repeat(1025) })).status, 413);
  assert.equal((await action('heat')).status, 200);
  await until(() => device()?.status === 'alert');
  assert.equal(hub.snapshot().devices[1]!.status, 'online');
  assert.equal((await action('stop')).status, 200);
  await until(() => device()?.status === 'offline');
  const losses = device()!.lost;
  assert.equal((await action('normal')).status, 200);
  await until(() => device()?.status === 'online'); assert.equal(device()!.lost, losses);
  await until(() => demo.snapshot().devices[0]!.canRestart);
  assert.equal((await action('restart')).status, 200);
  await until(() => device()?.restarts === 1);
  assert.equal(device()!.status, 'online'); assert.equal(device()!.lost, losses);
  assert.equal(hub.snapshot().devices[1]!.restarts, 0);
  assert.ok(hub.snapshot().counters.received > initial);
  assert.equal(hub.snapshot().counters.invalid, 0);
  assert.equal(demo.snapshot().actions[0]!.label, 'Redémarrage demandé');
  await hub.close(); await until(() => !demo.snapshot().hub.connected);
  await demo.close(); await demo.close();
});
